def report(sources, *classes):
    """A minimal Cobertura document: `classes` are (filename, {line: hits}) pairs."""
    source_xml = ''.join(f'<source>{source}</source>' for source in sources)
    class_xml = ''.join(
        f'<class filename="{name}"><lines>'
        + ''.join(f'<line number="{line}" hits="{hits}"/>' for line, hits in lines.items())
        + '</lines></class>' for name, lines in classes)
    return (f'<coverage><sources>{source_xml}</sources><packages><package><classes>'
            f'{class_xml}</classes></package></packages></coverage>')


class ParseTest(unittest.TestCase):
    def setUp(self):
        self.root = self.enterContext(tempfile.TemporaryDirectory())
        self.out = io.StringIO()
        redirect = contextlib.redirect_stdout(self.out)
        redirect.__enter__()
        self.addCleanup(redirect.__exit__, None, None, None)

    def write(self, text, files=()):
        for name in files:
            Path(self.root, name).parent.mkdir(parents=True, exist_ok=True)
            Path(self.root, name).write_bytes(b'x\n')
        path = Path(self.root, 'coverage.xml')
        path.write_bytes(text.encode('utf-8') if isinstance(text, str) else text)
        return path

    def parse(self, text, files=(), root=None):
        return cobertura.parse(self.write(text, files), root or self.root)

    def test_real_coverage_py_report_with_two_sources(self):
        text = COVERAGE_PY_TWO_SOURCES.replace('ROOT', self.root)
        self.assertEqual(self.parse(text, COVERAGE_PY_FILES), COVERAGE_PY_LINES)

    def test_real_vitest_report_reads_class_lines_not_method_lines(self):
        text = VITEST_COBERTURA.replace('ROOT', self.root)
        self.assertEqual(self.parse(text), {'src/lib.js': {1: 1, 2: 1, 3: 0, 4: 0, 5: 1, 6: 1}})

    def test_windows_separators_and_drive_letters(self):
        for source, filename in (('D:\\a\\r\\r', 'pkg\\mod.py'), ('d:\\a\\r\\r', 'pkg/mod.py'),
                                 ('D:/a/r/r/pkg', 'mod.py'), ('', 'D:\\a\\r\\r\\pkg\\mod.py')):
            with self.subTest(source=source, filename=filename):
                sources = [source] if source else []
                self.assertEqual(self.parse(report(sources, (filename, {3: 2})),
                                            root='D:\\a\\r\\r'), {'pkg/mod.py': {3: 2}})

    def test_paths_resolve_against_the_source_or_the_root(self):
        for sources, filename, expected in (
                ([], 'pkg/mod.py', 'pkg/mod.py'),
                (['.'], './pkg/mod.py', 'pkg/mod.py'),
                (['pkg'], 'mod.py', 'pkg/mod.py'),
                (['ROOT'], 'pkg/../lib/x.py', 'lib/x.py'),
                (['ROOT/pkg'], 'ROOT/lib/x.py', 'lib/x.py')):
            with self.subTest(sources=sources, filename=filename):
                sources = [source.replace('ROOT', self.root) for source in sources]
                text = report(sources, (filename.replace('ROOT', self.root), {1: 1}))
                self.assertEqual(self.parse(text), {expected: {1: 1}})

    def test_files_outside_the_root_are_dropped(self):
        outside = str(Path(self.root).parent / 'elsewhere.py')
        for sources, filename in (([], outside), (['.'], '../x.py'), ([outside], 'x.py'),
                                  ([], self.root + 'x/sibling.py'), ([], self.root)):
            with self.subTest(sources=sources, filename=filename):
                kept = os.path.join(self.root, 'kept.py')
                text = report(sources, (filename, {1: 1}), (kept, {2: 0}))
                self.assertEqual(self.parse(text), {'kept.py': {2: 0}})

    @unittest.skipUnless(hasattr(os, 'symlink'), 'needs symlinks')
    def test_a_report_naming_the_real_path_of_a_symlinked_root(self):
        real = Path(self.root, 'real')
        real.mkdir()
        link = Path(self.root, 'link')
        os.symlink(real, link)
        text = report([os.path.realpath(real)], ('pkg/mod.py', {1: 1}))
        for root in (str(link), os.path.relpath(link)):
            with self.subTest(root=root):
                self.assertEqual(cobertura.parse(self.write(text), root), {'pkg/mod.py': {1: 1}})

    def test_several_sources_pick_the_one_holding_the_file(self):
        text = report(['a', 'b'], ('mod.py', {1: 1}))
        self.assertEqual(self.parse(text, ['b/mod.py']), {'b/mod.py': {1: 1}})
        self.assertEqual(self.out.getvalue(), '')

    def test_several_sources_holding_the_file_or_none_drop_it_with_a_warning(self):
        for files, word in ((['a/mod.py', 'b/mod.py'], 'several'), ([], 'no')):
            with self.subTest(files=files):
                self.out.truncate(0)
                self.out.seek(0)
                with tempfile.TemporaryDirectory() as root:
                    self.root = root
                    text = report(['a', 'b'], ('mod.py', {1: 1}), ('a/b.py', {1: 1}))
                    self.assertEqual(self.parse(text, files + ['a/a/b.py']), {'a/a/b.py': {1: 1}})
                self.assertTrue(self.out.getvalue().startswith('::warning::'), self.out.getvalue())
                self.assertIn('mod.py', self.out.getvalue())
                self.assertIn(word, self.out.getvalue())

    def test_method_lines_are_not_class_lines(self):
        text = ('<coverage><packages><package><classes><class filename="a.py"><methods><method>'
                '<lines><line number="5" hits="3"/></lines></method></methods>'
                '<lines><line number="1" hits="0"/></lines></class></classes></package>'
                '</packages></coverage>')
        self.assertEqual(self.parse(text), {'a.py': {1: 0}})

    def test_one_file_in_several_classes_keeps_the_highest_hits(self):
        text = report([], ('a.py', {1: 0, 2: 3}), ('a.py', {1: 2, 2: 1, 5: 0}))
        self.assertEqual(self.parse(text), {'a.py': {1: 2, 2: 3, 5: 0}})

    def test_invalid_reports_are_configuration_errors_naming_the_file(self):
        for text in (b'not xml', b'<junit/>', report([], ('a.py', {'x': 1})),
                     report([], ('a.py', {0: 1})), report([], ('a.py', {1: -1})),
                     report([], ('a.py', {1: 'many'})),
                     '<coverage><packages><package><classes><class><lines/></class></classes>'
                     '</package></packages></coverage>',
                     b'<?xml version="1.0"?><!DOCTYPE coverage [<!ENTITY e "x">]>'
                     b'<coverage>&e;</coverage>'):
            with self.subTest(text=text):
                with self.assertRaises(ConfigError) as caught:
                    self.parse(text)
                self.assertIn('coverage.xml', str(caught.exception))

    def test_a_missing_report_is_a_configuration_error(self):
        with self.assertRaisesRegex(ConfigError, 'absent.xml'):
            cobertura.parse(Path(self.root, 'absent.xml'), self.root)


class DumpTest(unittest.TestCase):
    LINES = {'src/b.py': {4: 0, 2: 3}, 'src/a.py': {1: 1, 2: 0, 3: 0}, 'empty.py': {}}

    def test_the_written_report_reads_back_identically_from_any_root(self):
        with tempfile.TemporaryDirectory() as root:
            path = Path(root, 'out.xml')
            path.write_text(cobertura.dump(self.LINES), encoding='utf-8')
            self.assertEqual(cobertura.parse(path, root), self.LINES)

    def test_its_shape_is_one_class_per_file_under_the_dot_source(self):
        document = ET.fromstring(cobertura.dump(self.LINES))
        self.assertEqual([source.text for source in document.iter('source')], ['.'])
        classes = list(document.iter('class'))
        self.assertEqual([item.get('filename') for item in classes],
                         ['empty.py', 'src/a.py', 'src/b.py'])
        self.assertEqual([item.get('line-rate') for item in classes], ['1', '0.3333', '0.5'])
        self.assertEqual([line.get('number') for line in classes[2].iter('line')], ['2', '4'])
        self.assertEqual((document.get('lines-valid'), document.get('lines-covered'),
                          document.get('line-rate')), ('5', '2', '0.4'))

    def test_an_empty_mapping_is_a_valid_report(self):
        document = ET.fromstring(cobertura.dump({}))
        self.assertEqual((document.tag, document.get('lines-valid'), document.get('line-rate')),
                         ('coverage', '0', '1'))


class MergeTest(unittest.TestCase):
    def test_a_line_is_covered_when_any_input_covered_it(self):
        merged = cobertura.merge([{'a.py': {1: 0, 2: 2}, 'b.py': {1: 0}},
                                  {'a.py': {1: 3, 2: 1, 3: 0}}, {'c.py': {7: 1}}, {}])
        # Hits add up across inputs: each counts its own executions of the line.
        self.assertEqual(merged, {'a.py': {1: 3, 2: 3, 3: 0}, 'b.py': {1: 0}, 'c.py': {7: 1}})

    def test_merging_leaves_its_inputs_untouched(self):
        first = {'a.py': {1: 1}}
        cobertura.merge([first, {'a.py': {1: 1}}])
        self.assertEqual(first, {'a.py': {1: 1}})
